def write():
    root = os.path.join(os.path.dirname(__file__), '..', 'lib', 'core', 'localization', 'arb')
    os.makedirs(root, exist_ok=True)
    for idx, locale in enumerate(['en', 'ne']):
        out = {'@@locale': locale}
        for k, pair in S.items():
            out[k] = pair[idx]
            if idx == 0 and k in P:
                out['@' + k] = {'placeholders': {n: {'type': t} for n, t in P[k].items()}}
        with open(os.path.join(root, f'app_{locale}.arb'), 'w', encoding='utf-8') as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print(f'{len(S)} strings written')


if __name__ == '__main__':
    write()
